export const plans = {
  '2-1': r => { r.grade(1); r.skill(); r.land(); r.finish(); },
  '2-2': r => { r.skill(); r.land(); r.skill(); r.until(g => g.body.grounded && g.state !== 'thrown' && g.state !== 'lift', 4, { right: true }); r.land(); r.finish(); },
  '2-3': r => {
    r.grade(1); r.skill(); r.land();
    r.until(g => g.body.x <= 620, 3, { left: true }); r.world();
    for (const [x, y] of [[680, 560], [760, 480], [840, 400], [920, 320]]) r.stair(x, y);
    r.skill(); r.land(); r.finish();
  },
  '2-4': r => {
    for (const [x, y] of [[200, 560], [280, 480], [360, 400], [440, 320], [520, 240], [600, 160], [720, 160]]) r.stair(x, y);
    r.skill(); r.land();
    r.grade(-1); r.world(); r.land();
    r.grade(-1); r.world(); r.land(); r.finish({ left: true });
  },
  '2-5': r => {
    r.grade(1); r.skill(); r.land(); r.world();
    r.until(g => g.body.x >= 580, 3, { right: true });
    r.grade(1); r.skill(); r.land(); r.world(); r.land();
    r.grade(-1); r.world(); r.grade(-1); r.world();
    r.finish({ left: true });
  },
};
